  const normalize = (s) => s.replace(/\s+/g, ' ').trim();
  const reverse = new Map();
  for (const [key, values] of Object.entries(strings)) {
    reverse.set(normalize(key), key);
    for (const v of Object.values(values))
      if (!reverse.has(normalize(v))) reverse.set(normalize(v), key);
  }
  function translate(text) {
    const original = normalize(text),
      key = reverse.get(original);
    if (key) return language === 'en' ? key : strings[key][language];
    const retry = original.match(/^(.+) (Your message is still here\.)$/);
    if (retry) return translate(retry[1]) + ' ' + translate(retry[2]);
    const parts = original.split(' · ');
    if (parts.length > 1) return parts.map(translate).join(' · ');
    const tail = original.match(/^(.+?)(\s+[✦✓])$/u);
    if (tail) return translate(tail[1]) + tail[2];
    const decorated = original.match(/^([^\p{L}\p{N}]+)(.+?)(\s*[✦✓])?$/u);
    if (decorated)
      return decorated[1] + translate(decorated[2]) + (decorated[3] || '');
    const numbered = original.match(/^(Phrase|Zin|Satz|Frase) (\d+ \/ 20)$/);
    if (numbered) return translate('Phrase') + ' ' + numbered[2];
    const progress = original.match(
      /^(Speaking|Aan het spreken|Lecture en cours|Spricht|Hablando) (\d+%)$/,
    );
    if (progress) return translate('Speaking') + ' ' + progress[2];
    const sent = original.match(
      /^(.+) (sent|verzonden|envoyé|gesendet|enviada)$/,
    );
    if (sent) return translate(sent[1]) + ' ' + translate('sent');
    return original;
  }
  function skip(node) {
    const p = node.parentElement;
    if (!p) return true;
    if (
      p.closest(
        'script,style,svg,#bubble,#pair-code,#message,#demo-text,#ui-language,#local-language,#language,#demo-lang,header>a,header>div>span',
      )
    )
      return true;
    if (p.closest('#history') && !p.closest('small')) return true;
    if (
      p.closest('#local-voice,#remote-voice') &&
      p.tagName === 'OPTION' &&
      p.value !== ''
    )
      return true;
    return false;
  }
  const sources = new WeakMap(),
    attributes = new WeakMap();
  function apply() {
    document.documentElement.lang = language;
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    let node;
    while ((node = walker.nextNode())) {
      if (skip(node) || !node.nodeValue.trim()) continue;
      const cached = sources.get(node),
        source =
          cached?.last === node.nodeValue ? cached.source : node.nodeValue;
      const value = translate(source);
      if (normalize(node.nodeValue) !== value)
        node.nodeValue =
          (source.match(/^\s*/)?.[0] || '') +
          value +
          (source.match(/\s*$/)?.[0] || '');
      sources.set(node, { source, last: node.nodeValue });
    }
    for (const el of document.querySelectorAll('[aria-label],[placeholder]'))
      for (const attr of ['aria-label', 'placeholder']) {
        if (!el.hasAttribute(attr) || el.id === 'code') continue;
        let saved = attributes.get(el) || {};
        const current = el.getAttribute(attr),
          source = saved[attr]?.last === current ? saved[attr].source : current;
        const value = translate(source);
        if (value !== current) el.setAttribute(attr, value);
        saved[attr] = { source, last: value };
        attributes.set(el, saved);
      }
  }
  const picker = document.getElementById('ui-language');
  picker.value = language;
  picker.onchange = () => {
    language = langs.includes(picker.value) ? picker.value : 'en';
    try {
      localStorage.setItem('bear-ui-language', language);
    } catch {}
    apply();
  };
  new MutationObserver(() => apply()).observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['aria-label', 'placeholder'],
  });
